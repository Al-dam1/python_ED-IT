ingreso_usuario = int(input("Ingresa del 1 al 7: "))
if ingreso_usuario == 1 :
    print("LUNES")
elif ingreso_usuario == 2:
    print("MARTES")
elif ingreso_usuario == 3:
    print("MIERCOLES")
elif ingreso_usuario == 4:
    print("JUEVES")
elif ingreso_usuario == 5:
    print("VIERNES")
elif ingreso_usuario == 6:
    print("SABADO")
elif ingreso_usuario == 7:
    print("DOMINGO")
else:
    print("Numero ingresado INVALIDO!") 